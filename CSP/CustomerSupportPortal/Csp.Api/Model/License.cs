using System;
using Csp.Api.Model.Attributes;
using System.Data;
using Csp.Api.DataAccess.HelperClasses.Literals;
using Newtonsoft.Json;
using System.Collections.Generic;

namespace Csp.Api.Model {

	/// <summary>
	/// A license is for dynamic updates, software, service or support. 
	/// This table holds detailed licensing information, PAN service creates licensing entries when a sales order shipped by SAP. 
	/// More licensing information pushed to lic_features during authcode activation process. 
	/// There can be multiple entries based on the type of device and support shipped. 
	/// This table also updated during RMA process or transferring licenses.					
	/// </summary>
	public class License : AuditCspModel {
		public License() {

			Entitlement = new PartMaster();
			SupportProvider = new SupportAccount();
			Customer = new SupportAccount();

		}

		/// <summary>
		/// Lic_features id, primary key.
		/// </summary>
		[DataAccess(LicenseFields.LicenseId, DataType = DbType.Int64, UseForCreate = false)]
		public long Id {
			set;
			get;
		}


		/// <summary>
		/// Authcode generated by licensing service.
		/// </summary>
		[DataAccess(LicenseFields.AuthorizationCode)]
		public string AuthorizationCode {
			set;
			get;
		}


		/// <summary>
		/// Created by licensing service during the activation process. Used by the device to determine expiration etc.
		/// </summary>
		[DataAccess(LicenseFields.LicenseKey)]
		public string LicenseKey {
			set;
			get;
		}


		/// <summary>
		/// Support Account id which manages this. Foreign key to SupportAccount table.
		/// </summary>
		[DataAccessModel(DataType = DbType.Int64, PropertyName = "Id", StorageName = LicenseFields.SupportCenterSupportAccountId, UseKeyOnly = true)]
		public SupportAccount SupportProvider {
			set;
			get;
		}


		/// <summary>
		/// 
		/// </summary>
		[DataAccessModel(DataType = DbType.Int64, PropertyName = "Id", StorageName = LicenseFields.SupportAccountId, UseKeyOnly = true)]
		public SupportAccount Customer {
			set;
			get;
		}


		/// <summary>
		/// License part name.  In CSP schema Foreign key to the PartMaster table.
		/// </summary>
		[DataAccessModel(DataType = DbType.Int64, PropertyName = "Id", StorageName = LicenseFields.PartMasterId, UseKeyOnly = true)]
		public PartMaster Entitlement {
			set;
			get;
		}





		/// <summary>
		/// Device id to which the license is applied to.  In CSP schema Foreign key to the Device table.
		/// </summary>
		[DataAccess(LicenseFields.DeviceId, DataType = DbType.Int64)]
		public long DeviceId {
			set;
			get;
		}


		/// <summary>
		/// License effective date.
		/// </summary>
		[DataAccess(LicenseFields.EffectiveDate, DataType = DbType.DateTime)]
		public DateTime EffectiveDate {
			set;
			get;
		}


		/// <summary>
		/// Actual license activation date.
		/// </summary>
		[DataAccess(LicenseFields.RegistrationDate, DataType = DbType.DateTime)]
		public DateTime RegistrationDate {
			set;
			get;
		}


		/// <summary>
		/// License expiration date.
		/// </summary>
		[DataAccess(LicenseFields.ExpirationDate, DataType = DbType.DateTime)]
		public DateTime ExpirationDate {
			set;
			get;
		}


		/// <summary>
		/// Number of days given to activate the license. The billing starts after the end of grace period even if the license is not being activated.
		/// </summary>
		[DataAccess(LicenseFields.GracePeriodDays, DataType = DbType.Int32)]
		public Int32 GracePeriodDays {
			set;
			get;
		}


		/// <summary>
		/// Duration of the license in months.
		/// </summary>
		[DataAccess(LicenseFields.LicenseTermMonths, DataType = DbType.Int32)]
		public Int32 LicenseTermMonths {
			set;
			get;
		}


		/// <summary>
		/// Used for temporary license extension, referenced/map to Salesforce request id.
		/// </summary>
		[DataAccess(LicenseFields.ExtensionRequestSalesforceId, DataType = DbType.Int64)]
		public long ExtensionRequestSalesforceId {
			set;
			get;
		}


		/// <summary>
		/// This is field is linked back to the same table lfid field to get parent information. Used for chaining by licensing services. In CSP schema Foreign key to the same table.
		/// </summary>
		[DataAccess(LicenseFields.ParentLicenseId, DataType = DbType.Int64)]
		public long ParentLicenseId {
			set;
			get;
		}


		/// <summary>
		/// Bundle lfid is linked back to the same table lfid field to get bundle information in case of a license is part of Bundle package.  In CSP schema Foreign key to the same table.
		/// </summary>
		[DataAccess(LicenseFields.BundleLicenseId, DataType = DbType.Int64)]
		public long BundleLicenseId {
			set;
			get;
		}


		/// <summary>
		/// Ship date from SAP.
		/// </summary>
		[DataAccess(LicenseFields.ShipDate, DataType = DbType.DateTime)]
		public DateTime ShipDate {
			set;
			get;
		}


		/// <summary>
		/// Status of the License.
		/// </summary>
		[DataAccess(LicenseFields.IsActive, DataType = DbType.Int32)]
		public bool IsActive {
			set;
			get;
		}


		/// <summary>
		/// Notes added during activation.
		/// </summary>
		[DataAccess(LicenseFields.Notes)]
		public string Notes {
			set;
			get;
		}


		/// <summary>
		/// Shipment number pushed from SAP.
		/// </summary>
		[DataAccess(LicenseFields.ShipmentNumber, DataType = DbType.Int64)]
		public long ShipmentNumber {
			set;
			get;
		}


		/// <summary>
		/// Flag to make sure we are sync with SAP.
		/// </summary>
		[DataAccess(LicenseFields.IsSAPSynched, DataType = DbType.Int32)]
		public bool IsSAPSynched {
			set;
			get;
		}


		/// <summary>
		/// Used for site licenses, i.e. one license given to company for all devices with in the company.
		/// </summary>
		[DataAccess(LicenseFields.SiteLicenseSupportAccountId, DataType = DbType.Int64)]
		public long SiteLicenseSupportAccountId {
			set;
			get;
		}


		/// <summary>
		/// License activation city.
		/// </summary>
		[DataAccess(LicenseFields.City)]
		public string City {
			set;
			get;
		}


		/// <summary>
		/// License activation zip code.
		/// </summary>
		[DataAccess(LicenseFields.PostalCode)]
		public string PostalCode {
			set;
			get;
		}


		/// <summary>
		/// Billing country pushed from SAP. In CSP schema Foreign key to the Country table.
		/// </summary>
		[DataAccess(LicenseFields.BillToCountryId, DataType = DbType.Int64)]
		public long BillToCountryId {
			set;
			get;
		}

        [DataAccess(LicenseFields.CountryId,DataType = DbType.Int64)]
        public long CountryId
        {
            get;
            set;
        }


		/// <summary>
		/// Virtual machine quantity in case of authcode generated for virtual machine.
		/// </summary>
		[DataAccess(LicenseFields.VMQuantity, DataType = DbType.Int32)]
		public Int32 VMQuantity {
			set;
			get;
		}


		/// <summary>
		/// It’s like a device id to reference to device_master. 
		/// </summary>
		[DataAccess(LicenseFields.VMStubDeviceId, DataType = DbType.Int64)]
		public long VMStubDeviceId {
			set;
			get;
		}


		/// <summary>
		/// Same as parent id used for virtual machine.
		/// </summary>
		[DataAccess(LicenseFields.VMParentLicenseId, DataType = DbType.Int64)]
		public long VMParentLicenseId {
			set;
			get;
		}


		/// <summary>
		/// Usage count of the license in case of virtual machine.
		/// </summary>
		[DataAccess(LicenseFields.VMUseCount, DataType = DbType.Int32)]
		public Int32 VMUseCount {
			set;
			get;
		}
	}

    public class LicensingApi
    {
        public string LicensingApiKey { get; set; }
        public DateTime ExpirationDate { get; set; }
        public long SupportAccountId { get; set; }
        public long Days { get; set; }
    }

    public class ErrorDto
    {
        [JsonProperty(PropertyName = "error_message")]
        public string Error { get; set; }
    }

    public class BaseApiDto
    {
        [JsonProperty(PropertyName = "apiKey")]
        public string ApiKey { get; set; }

        [JsonProperty(PropertyName = "expirationDate")]
        public DateTime? ExpirationDate { get; set; }

        [JsonProperty(PropertyName = "licensingApiKeyId")]
        public long? LicensingApiKeyId { get; set; }

        [JsonProperty(PropertyName = "message")]
        public string ErrorMessage { get; set; }

    }

    public class ManageApiListDto
    {
        [JsonProperty(PropertyName = "licensingProductApiKeys")]
        public List<ManageApiDto> LicensingProductApiKeys { get; set; }

        [JsonProperty(PropertyName = "error_message")]
        public List<ErrorDto> Errors { get; set; }

        public ManageApiListDto()
        {
            LicensingProductApiKeys = new List<ManageApiDto>();
            Errors = new List<ErrorDto>();
        }
    }

    /// <summary>
    /// DataModel for all API details.
    /// </summary>
    public class ManageApiDto
    {
        [JsonProperty(PropertyName = "productId")]
        public long ProductId { get; set; }

        [JsonProperty(PropertyName = "name")]
        public string Name { get; set; }

        [JsonProperty(PropertyName = "details")]
        public BaseApiDto Details { get; set; }
    }

    public class ModifyApiDto : BaseApiDto
    {
        [JsonProperty(PropertyName = "timestamp")]
        public string TimeStamp { get; set; }

        [JsonProperty(PropertyName = "isKeyValid")]
        public bool? IsKeyValid { get; set; }

        [JsonProperty(PropertyName = "reason")]
        public string Reason { get; set; }

        [JsonProperty(PropertyName = "isSuccess")]
        public bool IsSuccess { get; set; }

        [JsonProperty(PropertyName = "successMessage")]
        public string SuccessMessage { get; set; }

        [JsonProperty(PropertyName = "error_message")]
        public List<ErrorDto> Errors { get; set; }

        public ModifyApiDto()
        {
            Errors = new List<ErrorDto>();
        }

    }

    public class PostApiDetails
    {
        [JsonProperty(PropertyName = "supportAccountId")]
        public long SupportAccountId { get; set; }

        [JsonProperty(PropertyName = "userAccountId")]
        public long UserAccountId { get; set; }

        [JsonProperty(PropertyName = "productId")]
        public int? ProductId { get; set; }

        [JsonProperty(PropertyName = "action")]
        public string ActionType { get; set; }

        [JsonProperty(PropertyName = "expirationDate")]
        public DateTime? ExpirationDate { get; set; }
    }

    public class PostDeleteApiDetails : PostApiDetails
    {

        [JsonProperty(PropertyName = "licensingApiKeyId")]
        public long? ApiKeyId { get; set; }
    }
}
